-- LOGIN: RECIBE USUARIO Y EL HASH SHA2 DE LA CONTRASENA (LO CALCULA LA APP), DEVUELVE ID, ROL Y MENSAJE (OUT)
CREATE PROCEDURE SP_LOGIN(
    IN P_USUARIO VARCHAR(30),
    IN P_PASSWORD_HASH CHAR(64),
    OUT P_ID_USUARIO INT,
    OUT P_ROL VARCHAR(30),
    OUT P_MENSAJE VARCHAR(200)
)
BEGIN
    DECLARE V_ESTADO VARCHAR(20);
    SET P_ID_USUARIO = NULL;
    SET P_ROL = NULL;
    SET V_ESTADO = NULL;

    SELECT U.ID_USUARIO, R.NOMBRE_ROL, U.ESTADO
      INTO P_ID_USUARIO, P_ROL, V_ESTADO
      FROM USUARIOS U
      JOIN ROLES R ON R.ID_ROL = U.ID_ROL
     WHERE U.NOMBRE_USUARIO = P_USUARIO
       AND U.CONTRASENA_HASH = P_PASSWORD_HASH;

    IF P_ID_USUARIO IS NULL THEN
        SET P_MENSAJE = 'USUARIO O CONTRASENA INCORRECTOS';
    ELSEIF V_ESTADO = 'INACTIVO' THEN
        SET P_ID_USUARIO = NULL;
        SET P_ROL = NULL;
        SET P_MENSAJE = 'LA CUENTA ESTA INACTIVA';
    ELSE
        SET P_MENSAJE = 'BIENVENIDO';
    END IF;
END$$

-- CONSULTAR UN EJEMPLAR POR CODIGO DE BARRAS (LO USA EL LECTOR)
CREATE PROCEDURE SP_CONSULTAR_EJEMPLAR(IN P_CODIGO VARCHAR(30))
BEGIN
    SELECT E.ID_EJEMPLAR, E.CODIGO_BARRAS, L.TITULO, L.AUTOR, L.ISBN,
           C.NOMBRE AS CATEGORIA, E.UBICACION, E.ESTADO,
           FN_DISPONIBLES_LIBRO(L.ID_LIBRO) AS COPIAS_DISPONIBLES,
           A.MATRICULA AS MATRICULA_ALUMNO,
           A.NOMBRE_COMPLETO AS PRESTADO_A,
           P.FECHA_LIMITE
      FROM EJEMPLARES E
      JOIN LIBROS L ON L.ID_LIBRO = E.ID_LIBRO
      JOIN CATEGORIAS C ON C.ID_CATEGORIA = L.ID_CATEGORIA
      LEFT JOIN PRESTAMOS P ON P.ID_EJEMPLAR = E.ID_EJEMPLAR AND P.ESTADO = 'ACTIVO'
      LEFT JOIN ALUMNOS A ON A.ID_ALUMNO = P.ID_ALUMNO
     WHERE E.CODIGO_BARRAS = P_CODIGO;
END$$

-- REGISTRAR PRESTAMO CON TRANSACCION
CREATE PROCEDURE SP_REGISTRAR_PRESTAMO(
    IN P_CODIGO VARCHAR(30),
    IN P_ID_ALUMNO INT,
    IN P_ID_USUARIO INT,
    IN P_DIAS INT,
    OUT P_MENSAJE VARCHAR(200)
)
BEGIN
    DECLARE V_ID_EJEMPLAR INT;

    -- SI ALGO FALLA INCLUYENDO LOS TRIGGERS SE CANCELA TODO
    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS CONDITION 1 @ERR_MSG = MESSAGE_TEXT;
        ROLLBACK;
        SET P_MENSAJE = CONCAT('ERROR: ', @ERR_MSG);
    END;

    SET V_ID_EJEMPLAR = NULL;
    IF P_DIAS IS NULL OR P_DIAS <= 0 THEN
        SET P_DIAS = 7;
    END IF;

    START TRANSACTION;

    SELECT ID_EJEMPLAR INTO V_ID_EJEMPLAR
      FROM EJEMPLARES
     WHERE CODIGO_BARRAS = P_CODIGO
       FOR UPDATE;

    IF V_ID_EJEMPLAR IS NULL THEN
        ROLLBACK;
        SET P_MENSAJE = 'ERROR: NO EXISTE UN EJEMPLAR CON ESE CODIGO DE BARRAS';
    ELSE
        INSERT INTO PRESTAMOS (ID_EJEMPLAR, ID_ALUMNO, ID_USUARIO, FECHA_PRESTAMO, FECHA_LIMITE, ESTADO)
        VALUES (V_ID_EJEMPLAR, P_ID_ALUMNO, P_ID_USUARIO, CURDATE(),
                DATE_ADD(CURDATE(), INTERVAL P_DIAS DAY), 'ACTIVO');

        UPDATE EJEMPLARES SET ESTADO = 'PRESTADO' WHERE ID_EJEMPLAR = V_ID_EJEMPLAR;

        COMMIT;
        SET P_MENSAJE = 'PRESTAMO REGISTRADO CORRECTAMENTE';
    END IF;
END$$

-- REGISTRAR DEVOLUCION CON TRANSACCION
CREATE PROCEDURE SP_REGISTRAR_DEVOLUCION(
    IN P_CODIGO VARCHAR(30),
    OUT P_DIAS_RETRASO INT,
    OUT P_MENSAJE VARCHAR(200)
)
BEGIN
    DECLARE V_ID_PRESTAMO INT;
    DECLARE V_ID_EJEMPLAR INT;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        GET DIAGNOSTICS CONDITION 1 @ERR_MSG = MESSAGE_TEXT;
        ROLLBACK;
        SET P_DIAS_RETRASO = 0;
        SET P_MENSAJE = CONCAT('ERROR: ', @ERR_MSG);
    END;

    SET V_ID_PRESTAMO = NULL;
    SET P_DIAS_RETRASO = 0;

    START TRANSACTION;

    SELECT P.ID_PRESTAMO, P.ID_EJEMPLAR
      INTO V_ID_PRESTAMO, V_ID_EJEMPLAR
      FROM PRESTAMOS P
      JOIN EJEMPLARES E ON E.ID_EJEMPLAR = P.ID_EJEMPLAR
     WHERE E.CODIGO_BARRAS = P_CODIGO AND P.ESTADO = 'ACTIVO'
     LIMIT 1
       FOR UPDATE;

    IF V_ID_PRESTAMO IS NULL THEN
        ROLLBACK;
        SET P_MENSAJE = 'ERROR: ESE EJEMPLAR NO TIENE UN PRESTAMO ACTIVO';
    ELSE
        UPDATE PRESTAMOS
           SET FECHA_DEVOLUCION = CURDATE(), ESTADO = 'DEVUELTO'
         WHERE ID_PRESTAMO = V_ID_PRESTAMO;

        UPDATE EJEMPLARES SET ESTADO = 'DISPONIBLE' WHERE ID_EJEMPLAR = V_ID_EJEMPLAR;

        COMMIT;
        SET P_DIAS_RETRASO = FN_DIAS_RETRASO(V_ID_PRESTAMO);
        SET P_MENSAJE = 'DEVOLUCION REGISTRADA CORRECTAMENTE';
    END IF;
END$$

-- DISPONIBILIDAD DE UN LIBRO (OUT)
CREATE PROCEDURE SP_DISPONIBILIDAD_LIBRO(
    IN P_ID_LIBRO INT,
    OUT P_TOTAL INT,
    OUT P_DISPONIBLES INT
)
BEGIN
    SELECT COUNT(*) INTO P_TOTAL FROM EJEMPLARES
     WHERE ID_LIBRO = P_ID_LIBRO AND ESTADO <> 'BAJA';
    SET P_DISPONIBLES = FN_DISPONIBLES_LIBRO(P_ID_LIBRO);
END$$

-- CAMBIAR UBICACION DE UN EJEMPLAR (DISPARA AUDITORIA)
CREATE PROCEDURE SP_CAMBIAR_UBICACION(
    IN P_CODIGO VARCHAR(30),
    IN P_NUEVA_UBICACION VARCHAR(50)
)
BEGIN
    UPDATE EJEMPLARES SET UBICACION = P_NUEVA_UBICACION WHERE CODIGO_BARRAS = P_CODIGO;
END$$

-- HISTORIAL DE PRESTAMOS DE UN ALUMNO POR MATRICULA
CREATE PROCEDURE SP_HISTORIAL_ALUMNO(IN P_MATRICULA VARCHAR(20))
BEGIN
    SELECT P.ID_PRESTAMO, L.TITULO, E.CODIGO_BARRAS, P.FECHA_PRESTAMO,
           P.FECHA_LIMITE, P.FECHA_DEVOLUCION, P.ESTADO,
           FN_DIAS_RETRASO(P.ID_PRESTAMO) AS DIAS_RETRASO
      FROM PRESTAMOS P
      JOIN ALUMNOS A ON A.ID_ALUMNO = P.ID_ALUMNO
      JOIN EJEMPLARES E ON E.ID_EJEMPLAR = P.ID_EJEMPLAR
      JOIN LIBROS L ON L.ID_LIBRO = E.ID_LIBRO
     WHERE A.MATRICULA = P_MATRICULA
     ORDER BY P.FECHA_PRESTAMO DESC;
END$$

