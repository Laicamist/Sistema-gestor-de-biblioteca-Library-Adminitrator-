-- NO PERMITIR CODIGO DE BARRAS VACIO AL INSERTAR EJEMPLAR
CREATE TRIGGER TRG_VAL_EJEMPLARES_BI
BEFORE INSERT ON EJEMPLARES
FOR EACH ROW
BEGIN
    IF NEW.CODIGO_BARRAS IS NULL OR TRIM(NEW.CODIGO_BARRAS) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'EL CODIGO DE BARRAS NO PUEDE ESTAR VACIO';
    END IF;
END$$

