-- 1. TABLAS

-- ROLES DE QUIEN USA EL SISTEMA (BIBLIOTECARIOS, ADMIN)
CREATE TABLE ROLES (
    ID_ROL INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE_ROL VARCHAR(30) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR(100)
);

-- PERSONAL DE LA BIBLIOTECA QUE INICIA SESION
CREATE TABLE USUARIOS (
    ID_USUARIO INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE_COMPLETO VARCHAR(100) NOT NULL,
    NOMBRE_USUARIO VARCHAR(30) NOT NULL UNIQUE,
    CONTRASENA_HASH CHAR(64) NOT NULL,            -- SHA2 256 (LO CALCULA LA APP)
    ID_ROL INT NOT NULL,
    ESTADO ENUM('ACTIVO','INACTIVO') NOT NULL DEFAULT 'ACTIVO',
    FOREIGN KEY (ID_ROL) REFERENCES ROLES(ID_ROL)
);

CREATE TABLE CARRERAS (
    ID_CARRERA INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE VARCHAR(80) NOT NULL UNIQUE
);

-- ESTUDIANTES DE LA UNIVERSIDAD QUE PIDEN LIBROS (NO INICIAN SESION)
CREATE TABLE ALUMNOS (
    ID_ALUMNO INT AUTO_INCREMENT PRIMARY KEY,
    MATRICULA VARCHAR(20) NOT NULL UNIQUE,
    NOMBRE_COMPLETO VARCHAR(100) NOT NULL,
    ID_CARRERA INT NOT NULL,
    SEMESTRE INT NOT NULL,
    CORREO VARCHAR(100),
    TELEFONO VARCHAR(15),
    ESTADO ENUM('ACTIVO','INACTIVO') NOT NULL DEFAULT 'ACTIVO',
    FOREIGN KEY (ID_CARRERA) REFERENCES CARRERAS(ID_CARRERA),
    CHECK (SEMESTRE BETWEEN 1 AND 12)
);

CREATE TABLE CATEGORIAS (
    ID_CATEGORIA INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE LIBROS (
    ID_LIBRO INT AUTO_INCREMENT PRIMARY KEY,
    ISBN VARCHAR(20) NOT NULL UNIQUE,
    TITULO VARCHAR(150) NOT NULL,
    AUTOR VARCHAR(100) NOT NULL,
    EDITORIAL VARCHAR(80),
    ANIO INT,
    ID_CATEGORIA INT NOT NULL,
    FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIAS(ID_CATEGORIA),
    CHECK (ANIO IS NULL OR ANIO > 0)
);

-- CADA EJEMPLAR FISICO TIENE SU PROPIO CODIGO DE BARRAS UNICO
CREATE TABLE EJEMPLARES (
    ID_EJEMPLAR INT AUTO_INCREMENT PRIMARY KEY,
    CODIGO_BARRAS VARCHAR(30) NOT NULL UNIQUE,
    ID_LIBRO INT NOT NULL,
    UBICACION VARCHAR(50) NOT NULL,
    ESTADO ENUM('DISPONIBLE','PRESTADO','MANTENIMIENTO','BAJA') NOT NULL DEFAULT 'DISPONIBLE',
    FOREIGN KEY (ID_LIBRO) REFERENCES LIBROS(ID_LIBRO),
    CHECK (CHAR_LENGTH(TRIM(CODIGO_BARRAS)) > 0)
);

CREATE TABLE PRESTAMOS (
    ID_PRESTAMO INT AUTO_INCREMENT PRIMARY KEY,
    ID_EJEMPLAR INT NOT NULL,
    ID_ALUMNO INT NOT NULL,
    ID_USUARIO INT NOT NULL,                      -- BIBLIOTECARIO QUE REGISTRO
    FECHA_PRESTAMO DATE NOT NULL,
    FECHA_LIMITE DATE NOT NULL,
    FECHA_DEVOLUCION DATE NULL,
    ESTADO ENUM('ACTIVO','DEVUELTO') NOT NULL DEFAULT 'ACTIVO',
    FOREIGN KEY (ID_EJEMPLAR) REFERENCES EJEMPLARES(ID_EJEMPLAR),
    FOREIGN KEY (ID_ALUMNO) REFERENCES ALUMNOS(ID_ALUMNO),
    FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS(ID_USUARIO),
    CHECK (FECHA_LIMITE >= FECHA_PRESTAMO)
);

CREATE TABLE AUDITORIA (
    ID_AUDITORIA INT AUTO_INCREMENT PRIMARY KEY,
    TABLA_AFECTADA VARCHAR(30) NOT NULL,
    OPERACION ENUM('INSERT','UPDATE','DELETE') NOT NULL,
    FECHA_HORA DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    USUARIO VARCHAR(100),
    DATOS_ANTERIORES JSON NULL,
    DATOS_NUEVOS JSON NULL
);

