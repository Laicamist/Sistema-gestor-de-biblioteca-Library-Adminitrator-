-- HISTORIAL DE PRESTAMOS DE UN ALUMNO POR MATRICULA
CREATE PROCEDURE SP_HISTORIAL_ALUMNO(IN P_MATRICULA VARCHAR(20))
BEGIN
    SELECT P.ID_PRESTAMO, L.TITULO, E.CODIGO_BARRAS, P.FECHA_PRESTAMO,
           P.FECHA_LIMITE, P.FECHA_DEVOLUCION, P.ESTADO,
           FN_DIAS_RETRASO(P.ID_PRESTAMO) AS DIAS_RETRASO
      FROM PRESTAMOS P
      JOIN ALUMNOS A ON A.ID_ALUMNO = P.ID_ALUMNO
      JOIN EJEMPLARES E ON E.ID_EJEMPLAR = P.ID_EJEMPLAR
      JOIN LIBROS L ON L.ID_LIBRO = E.ID_LIBRO
     WHERE A.MATRICULA = P_MATRICULA
     ORDER BY P.FECHA_PRESTAMO DESC;
END$$

