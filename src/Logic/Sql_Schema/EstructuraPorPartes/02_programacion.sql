-- 6. VISTAS PARA REPORTES

-- REPORTE 1: ALUMNOS CON PRESTAMOS VENCIDOS (JOIN DE 5 TABLAS + FUNCION)
CREATE VIEW V_PRESTAMOS_VENCIDOS AS
SELECT P.ID_PRESTAMO, A.MATRICULA, A.NOMBRE_COMPLETO AS ALUMNO,
       CA.NOMBRE AS CARRERA, A.CORREO,
       L.TITULO, E.CODIGO_BARRAS, P.FECHA_PRESTAMO, P.FECHA_LIMITE,
       FN_DIAS_RETRASO(P.ID_PRESTAMO) AS DIAS_RETRASO
  FROM PRESTAMOS P
  JOIN ALUMNOS A ON A.ID_ALUMNO = P.ID_ALUMNO
  JOIN CARRERAS CA ON CA.ID_CARRERA = A.ID_CARRERA
  JOIN EJEMPLARES E ON E.ID_EJEMPLAR = P.ID_EJEMPLAR
  JOIN LIBROS L ON L.ID_LIBRO = E.ID_LIBRO
 WHERE P.ESTADO = 'ACTIVO' AND P.FECHA_LIMITE < CURDATE();

-- REPORTE 2: LIBROS MAS SOLICITADOS (JOIN DE 4 TABLAS, GROUP BY, HAVING, COUNT, VENTANA RANK)
-- SOLO LIBROS CON AL MENOS 2 PRESTAMOS: LOS DE 1 PRESTAMO NO SE CONSIDERAN "SOLICITADOS"
CREATE VIEW V_LIBROS_MAS_SOLICITADOS AS
SELECT RANK() OVER (ORDER BY COUNT(P.ID_PRESTAMO) DESC) AS POSICION,
       L.ID_LIBRO, L.TITULO, L.AUTOR, C.NOMBRE AS CATEGORIA,
       COUNT(P.ID_PRESTAMO) AS TOTAL_PRESTAMOS
  FROM LIBROS L
  JOIN CATEGORIAS C ON C.ID_CATEGORIA = L.ID_CATEGORIA
  JOIN EJEMPLARES E ON E.ID_LIBRO = L.ID_LIBRO
  JOIN PRESTAMOS P ON P.ID_EJEMPLAR = E.ID_EJEMPLAR
 GROUP BY L.ID_LIBRO, L.TITULO, L.AUTOR, C.NOMBRE
HAVING COUNT(P.ID_PRESTAMO) >= 2;

-- REPORTE 1B: ALUMNOS CON PRESTAMOS VENCIDOS, AGRUPADOS POR ALUMNO
-- TECNICAS: CTE (WITH), JOIN DE 3 TABLAS (PRESTAMOS EN LA CTE + ALUMNOS + CARRERAS),
-- FUNCION ALMACENADA, COUNT/SUM/MAX, GROUP BY,
-- FUNCION DE VENTANA RANK() (EL QUE MAS DIAS DEBE QUEDA PRIMERO)
CREATE VIEW V_ALUMNOS_CON_VENCIDOS AS
WITH VENCIDOS AS (
    SELECT P.ID_ALUMNO, FN_DIAS_RETRASO(P.ID_PRESTAMO) AS DIAS
      FROM PRESTAMOS P
     WHERE P.ESTADO = 'ACTIVO' AND P.FECHA_LIMITE < CURDATE()
)
SELECT RANK() OVER (ORDER BY SUM(V.DIAS) DESC) AS POSICION,
       A.MATRICULA, A.NOMBRE_COMPLETO AS ALUMNO, CA.NOMBRE AS CARRERA, A.CORREO,
       COUNT(*) AS LIBROS_VENCIDOS,
       CAST(SUM(V.DIAS) AS SIGNED) AS TOTAL_DIAS_RETRASO,
       MAX(V.DIAS) AS MAX_DIAS_RETRASO
  FROM VENCIDOS V
  JOIN ALUMNOS A ON A.ID_ALUMNO = V.ID_ALUMNO
  JOIN CARRERAS CA ON CA.ID_CARRERA = A.ID_CARRERA
 GROUP BY A.ID_ALUMNO, A.MATRICULA, A.NOMBRE_COMPLETO, CA.NOMBRE, A.CORREO;

-- EXTRA: LIBROS QUE NUNCA SE HAN PRESTADO (NOT EXISTS)
CREATE VIEW V_LIBROS_SIN_PRESTAMOS AS
SELECT L.ID_LIBRO, L.TITULO, L.AUTOR
  FROM LIBROS L
 WHERE NOT EXISTS (
        SELECT 1 FROM EJEMPLARES E
          JOIN PRESTAMOS P ON P.ID_EJEMPLAR = E.ID_EJEMPLAR
         WHERE E.ID_LIBRO = L.ID_LIBRO);

-- EXTRA: DISPONIBILIDAD POR LIBRO
CREATE VIEW V_DISPONIBILIDAD AS
SELECT L.ID_LIBRO, L.TITULO, L.AUTOR,
       (SELECT COUNT(*) FROM EJEMPLARES E WHERE E.ID_LIBRO = L.ID_LIBRO AND E.ESTADO <> 'BAJA') AS TOTAL_EJEMPLARES,
       FN_DISPONIBLES_LIBRO(L.ID_LIBRO) AS DISPONIBLES
  FROM LIBROS L;
