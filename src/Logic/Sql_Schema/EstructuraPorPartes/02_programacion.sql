-- DIAS DE RETRASO DE UN PRESTAMO 0 SI NO HAY RETRASO
CREATE FUNCTION FN_DIAS_RETRASO(P_ID_PRESTAMO INT)
RETURNS INT
READS SQL DATA
BEGIN
    DECLARE V_LIMITE DATE;
    DECLARE V_DEVOLUCION DATE;
    SET V_LIMITE = NULL;

    SELECT FECHA_LIMITE, FECHA_DEVOLUCION
      INTO V_LIMITE, V_DEVOLUCION
      FROM PRESTAMOS
     WHERE ID_PRESTAMO = P_ID_PRESTAMO;

    IF V_LIMITE IS NULL THEN
        RETURN 0;
    END IF;

    RETURN GREATEST(DATEDIFF(COALESCE(V_DEVOLUCION, CURDATE()), V_LIMITE), 0);
END$$

-- CUANTOS EJEMPLARES DISPONIBLES TIENE UN LIBRO
CREATE FUNCTION FN_DISPONIBLES_LIBRO(P_ID_LIBRO INT)
RETURNS INT
READS SQL DATA
BEGIN
    DECLARE V_TOTAL INT;
    SELECT COUNT(*) INTO V_TOTAL
      FROM EJEMPLARES
     WHERE ID_LIBRO = P_ID_LIBRO AND ESTADO = 'DISPONIBLE';
    RETURN V_TOTAL;
END$$

-- 1 SI EL EJEMPLAR POR CODIGO DE BARRAS ESTA DISPONIBLE, 0 SI NO
CREATE FUNCTION FN_EJEMPLAR_DISPONIBLE(P_CODIGO VARCHAR(30))
RETURNS TINYINT
READS SQL DATA
BEGIN
    DECLARE V_CUENTA INT;
    SELECT COUNT(*) INTO V_CUENTA
      FROM EJEMPLARES
     WHERE CODIGO_BARRAS = P_CODIGO AND ESTADO = 'DISPONIBLE';
    RETURN IF(V_CUENTA > 0, 1, 0);
END$$

-- 3. TRIGGERS DE VALIDACION

-- NO PERMITIR CODIGO DE BARRAS VACIO AL INSERTAR EJEMPLAR
CREATE TRIGGER TRG_VAL_EJEMPLARES_BI
BEFORE INSERT ON EJEMPLARES
FOR EACH ROW
BEGIN
    IF NEW.CODIGO_BARRAS IS NULL OR TRIM(NEW.CODIGO_BARRAS) = '' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'EL CODIGO DE BARRAS NO PUEDE ESTAR VACIO';
    END IF;
END$$

