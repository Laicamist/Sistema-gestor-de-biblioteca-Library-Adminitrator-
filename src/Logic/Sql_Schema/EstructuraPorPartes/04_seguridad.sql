-- 04. USUARIOS, ROLES Y PERMISOS DE MYSQL
-- CADA ROL DE LA APLICACION SE CONECTA CON SU PROPIO USUARIO DE MYSQL.
-- ASI, AUNQUE ALGUIEN SE SALTARA LA VALIDACION DE PYTHON, MYSQL TAMBIEN LO DETIENE.
-- LAS CONTRASENAS SON SOLO PARA EL EQUIPO DE PRUEBA/EVALUACION; DEBEN COINCIDIR CON EL .env

USE BIBLIOTECA;

DROP USER IF EXISTS 'BIB_LOGIN'@'localhost';
DROP USER IF EXISTS 'BIB_ADMIN'@'localhost';
DROP USER IF EXISTS 'BIB_BIBLIOTECARIO'@'localhost';
DROP USER IF EXISTS 'BIB_CONSULTA'@'localhost';

CREATE USER 'BIB_LOGIN'@'localhost' IDENTIFIED BY 'LOGIN_BD_123';
CREATE USER 'BIB_ADMIN'@'localhost' IDENTIFIED BY 'ADMIN_BD_123';
CREATE USER 'BIB_BIBLIOTECARIO'@'localhost' IDENTIFIED BY 'BIBLIO_BD_123';
CREATE USER 'BIB_CONSULTA'@'localhost' IDENTIFIED BY 'CONS_BD_123';

-- LOGIN: LO UNICO QUE PUEDE HACER ANTES DE INICIAR SESION ES EJECUTAR SP_LOGIN.
-- NO PUEDE LEER USUARIOS NI LOS HASHES: EL SP CORRE CON LOS PERMISOS DE SU DEFINER.
GRANT EXECUTE ON PROCEDURE BIBLIOTECA.SP_LOGIN TO 'BIB_LOGIN'@'localhost';

-- ADMINISTRADOR: CRUD COMPLETO SOBRE LAS TABLAS DEL SISTEMA Y EJECUTA TODO,
-- PERO LA AUDITORIA ES DE SOLO LECTURA (NADIE PUEDE BORRAR O ALTERAR LA BITACORA;
-- LA ESCRIBEN LOS TRIGGERS CON LOS PERMISOS DE SU DEFINER).
GRANT SELECT, INSERT, UPDATE, DELETE ON BIBLIOTECA.ROLES      TO 'BIB_ADMIN'@'localhost';
GRANT SELECT, INSERT, UPDATE, DELETE ON BIBLIOTECA.USUARIOS   TO 'BIB_ADMIN'@'localhost';
GRANT SELECT, INSERT, UPDATE, DELETE ON BIBLIOTECA.CARRERAS   TO 'BIB_ADMIN'@'localhost';
GRANT SELECT, INSERT, UPDATE, DELETE ON BIBLIOTECA.ALUMNOS    TO 'BIB_ADMIN'@'localhost';
GRANT SELECT, INSERT, UPDATE, DELETE ON BIBLIOTECA.CATEGORIAS TO 'BIB_ADMIN'@'localhost';
GRANT SELECT, INSERT, UPDATE, DELETE ON BIBLIOTECA.LIBROS     TO 'BIB_ADMIN'@'localhost';
GRANT SELECT, INSERT, UPDATE, DELETE ON BIBLIOTECA.EJEMPLARES TO 'BIB_ADMIN'@'localhost';
GRANT SELECT ON BIBLIOTECA.PRESTAMOS  TO 'BIB_ADMIN'@'localhost';   -- SE MODIFICAN SOLO CON LOS SP
GRANT SELECT ON BIBLIOTECA.AUDITORIA  TO 'BIB_ADMIN'@'localhost';
GRANT SELECT ON BIBLIOTECA.V_PRESTAMOS_VENCIDOS     TO 'BIB_ADMIN'@'localhost';
GRANT SELECT ON BIBLIOTECA.V_ALUMNOS_CON_VENCIDOS   TO 'BIB_ADMIN'@'localhost';
GRANT SELECT ON BIBLIOTECA.V_LIBROS_MAS_SOLICITADOS TO 'BIB_ADMIN'@'localhost';
GRANT SELECT ON BIBLIOTECA.V_LIBROS_SIN_PRESTAMOS   TO 'BIB_ADMIN'@'localhost';
GRANT SELECT ON BIBLIOTECA.V_DISPONIBILIDAD         TO 'BIB_ADMIN'@'localhost';
GRANT EXECUTE ON BIBLIOTECA.* TO 'BIB_ADMIN'@'localhost';

-- BIBLIOTECARIO: CATALOGO Y ALUMNOS (ALTA Y CAMBIOS, SIN BORRAR).
-- PRESTAMOS SOLO A TRAVES DE SP_REGISTRAR_PRESTAMO / SP_REGISTRAR_DEVOLUCION,
-- PARA QUE NUNCA SE SALTE LA TRANSACCION. NO VE USUARIOS NI AUDITORIA.
GRANT SELECT ON BIBLIOTECA.CARRERAS   TO 'BIB_BIBLIOTECARIO'@'localhost';
GRANT SELECT ON BIBLIOTECA.CATEGORIAS TO 'BIB_BIBLIOTECARIO'@'localhost';
GRANT SELECT ON BIBLIOTECA.PRESTAMOS  TO 'BIB_BIBLIOTECARIO'@'localhost';
GRANT SELECT, INSERT, UPDATE ON BIBLIOTECA.LIBROS     TO 'BIB_BIBLIOTECARIO'@'localhost';
GRANT SELECT, INSERT, UPDATE ON BIBLIOTECA.EJEMPLARES TO 'BIB_BIBLIOTECARIO'@'localhost';
GRANT SELECT, INSERT, UPDATE ON BIBLIOTECA.ALUMNOS    TO 'BIB_BIBLIOTECARIO'@'localhost';
GRANT SELECT ON BIBLIOTECA.V_PRESTAMOS_VENCIDOS     TO 'BIB_BIBLIOTECARIO'@'localhost';
GRANT SELECT ON BIBLIOTECA.V_ALUMNOS_CON_VENCIDOS   TO 'BIB_BIBLIOTECARIO'@'localhost';
GRANT SELECT ON BIBLIOTECA.V_LIBROS_MAS_SOLICITADOS TO 'BIB_BIBLIOTECARIO'@'localhost';
GRANT SELECT ON BIBLIOTECA.V_LIBROS_SIN_PRESTAMOS   TO 'BIB_BIBLIOTECARIO'@'localhost';
GRANT SELECT ON BIBLIOTECA.V_DISPONIBILIDAD         TO 'BIB_BIBLIOTECARIO'@'localhost';
GRANT EXECUTE ON PROCEDURE BIBLIOTECA.SP_CONSULTAR_EJEMPLAR   TO 'BIB_BIBLIOTECARIO'@'localhost';
GRANT EXECUTE ON PROCEDURE BIBLIOTECA.SP_REGISTRAR_PRESTAMO   TO 'BIB_BIBLIOTECARIO'@'localhost';
GRANT EXECUTE ON PROCEDURE BIBLIOTECA.SP_REGISTRAR_DEVOLUCION TO 'BIB_BIBLIOTECARIO'@'localhost';
GRANT EXECUTE ON PROCEDURE BIBLIOTECA.SP_DISPONIBILIDAD_LIBRO TO 'BIB_BIBLIOTECARIO'@'localhost';
GRANT EXECUTE ON PROCEDURE BIBLIOTECA.SP_CAMBIAR_UBICACION    TO 'BIB_BIBLIOTECARIO'@'localhost';
GRANT EXECUTE ON PROCEDURE BIBLIOTECA.SP_HISTORIAL_ALUMNO     TO 'BIB_BIBLIOTECARIO'@'localhost';

-- CONSULTA: SOLO LEE REPORTES Y CONSULTA POR CODIGO DE BARRAS. NO MODIFICA NADA.
GRANT SELECT ON BIBLIOTECA.V_PRESTAMOS_VENCIDOS     TO 'BIB_CONSULTA'@'localhost';
GRANT SELECT ON BIBLIOTECA.V_ALUMNOS_CON_VENCIDOS   TO 'BIB_CONSULTA'@'localhost';
GRANT SELECT ON BIBLIOTECA.V_LIBROS_MAS_SOLICITADOS TO 'BIB_CONSULTA'@'localhost';
GRANT SELECT ON BIBLIOTECA.V_LIBROS_SIN_PRESTAMOS   TO 'BIB_CONSULTA'@'localhost';
GRANT SELECT ON BIBLIOTECA.V_DISPONIBILIDAD         TO 'BIB_CONSULTA'@'localhost';
GRANT EXECUTE ON PROCEDURE BIBLIOTECA.SP_CONSULTAR_EJEMPLAR   TO 'BIB_CONSULTA'@'localhost';
GRANT EXECUTE ON PROCEDURE BIBLIOTECA.SP_DISPONIBILIDAD_LIBRO TO 'BIB_CONSULTA'@'localhost';
GRANT EXECUTE ON PROCEDURE BIBLIOTECA.SP_HISTORIAL_ALUMNO     TO 'BIB_CONSULTA'@'localhost';
-- BIB_CONSULTA TAMBIEN PUEDE HACER EL LOGIN, POR SI EL .env USA ESTE USUARIO PARA DB_USER_LOGIN
-- (BIB_LOGIN ES LA OPCION MAS RESTRINGIDA: SOLO PUEDE EJECUTAR SP_LOGIN)
GRANT EXECUTE ON PROCEDURE BIBLIOTECA.SP_LOGIN                TO 'BIB_CONSULTA'@'localhost';

FLUSH PRIVILEGES;
