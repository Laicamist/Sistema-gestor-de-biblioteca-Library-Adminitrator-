-- SOLO SE BORRA UN EJEMPLAR DADO DE BAJA (PASA AL ELIMINAR SU LIBRO).
-- SI TIENE PRESTAMOS EN EL HISTORIAL, LA LLAVE FORANEA DE PRESTAMOS TAMBIEN LO IMPIDE.
CREATE TRIGGER TRG_VAL_EJEMPLARES_BD
BEFORE DELETE ON EJEMPLARES
FOR EACH ROW
BEGIN
    IF OLD.ESTADO <> 'BAJA' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'SOLO SE PUEDE ELIMINAR UN EJEMPLAR DADO DE BAJA';
    END IF;
END$$

-- VALIDAR UN PRESTAMO NUEVO
CREATE TRIGGER TRG_VAL_PRESTAMOS_BI
BEFORE INSERT ON PRESTAMOS
FOR EACH ROW
BEGIN
    DECLARE V_ESTADO_EJ VARCHAR(20);
    DECLARE V_ESTADO_ALUMNO VARCHAR(20);
    DECLARE V_ACTIVOS INT;

    IF NEW.ESTADO = 'ACTIVO' THEN
        SELECT ESTADO INTO V_ESTADO_EJ FROM EJEMPLARES WHERE ID_EJEMPLAR = NEW.ID_EJEMPLAR;
        IF V_ESTADO_EJ <> 'DISPONIBLE' THEN
            SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'EL EJEMPLAR NO ESTA DISPONIBLE PARA PRESTAMO';
        END IF;

        SELECT ESTADO INTO V_ESTADO_ALUMNO FROM ALUMNOS WHERE ID_ALUMNO = NEW.ID_ALUMNO;
        IF V_ESTADO_ALUMNO <> 'ACTIVO' THEN
            SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'EL ALUMNO ESTA INACTIVO (DADO DE BAJA)';
        END IF;

        SELECT COUNT(*) INTO V_ACTIVOS
          FROM PRESTAMOS
         WHERE ID_ALUMNO = NEW.ID_ALUMNO AND ESTADO = 'ACTIVO';
        IF V_ACTIVOS >= 3 THEN
            SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'EL ALUMNO YA TIENE 3 PRESTAMOS ACTIVOS';
        END IF;
    END IF;
END$$

-- VALIDAR AL ACTUALIZAR UN PRESTAMO (DEVOLUCION)
CREATE TRIGGER TRG_VAL_PRESTAMOS_BU
BEFORE UPDATE ON PRESTAMOS
FOR EACH ROW
BEGIN
    IF OLD.ESTADO = 'DEVUELTO' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ESTE PRESTAMO YA FUE DEVUELTO, NO SE PUEDE MODIFICAR';
    END IF;

    IF NEW.FECHA_DEVOLUCION IS NOT NULL AND NEW.FECHA_DEVOLUCION < OLD.FECHA_PRESTAMO THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'LA FECHA DE DEVOLUCION NO PUEDE SER ANTERIOR AL PRESTAMO';
    END IF;
END$$


